# ─────────────────────────────────────────────────────────────────────────────
# Fonction de traduction principale
# Usage : tr("nav_dashboard", lang())  — retourne la chaîne dans la langue
# ─────────────────────────────────────────────────────────────────────────────
tr <- function(key, lang = "fr") {
  val <- TRANSLATIONS[[lang]][[key]]
  if (is.null(val)) {
    # Fallback : FR si la clé EN n'existe pas encore
    TRANSLATIONS[["fr"]][[key]] %||% key
  } else {
    val
  }
}

# Opérateur null-coalescing (si pas déjà chargé)
if (!exists("%||%")) {
  `%||%` <- function(a, b) if (!is.null(a)) a else b
}
